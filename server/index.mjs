import { mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import webpush from 'web-push';
import { openStore } from './store.mjs';
import { createApp } from './http.mjs';
import { createMonitor } from './monitor.mjs';
import { createHandler } from '../tracker/api.mjs';
process.umask(0o077);
const config = { origin: process.env.APP_ORIGIN || '', sessionSecret: process.env.SESSION_SECRET || '' };
if (!/^[a-f0-9]{64}$/.test(config.sessionSecret) || !process.env.NS_API_SUBSCRIPTION_KEY) throw Error('Missing/invalid configuration. Run the setup script before starting.');
if (!config.origin) throw Error('APP_ORIGIN is required. Set your public HTTPS origin in the environment.');
const origin = new URL(config.origin);
if (origin.protocol !== 'https:' || origin.origin !== config.origin) throw Error('APP_ORIGIN must be an HTTPS origin without a trailing slash.');
const seconds = Number(process.env.POLL_SECONDS || 30);
if (!Number.isInteger(seconds) || seconds < 15 || seconds > 300) throw Error('POLL_SECONDS must be 15–300.');
const dir = resolve(process.env.DATA_DIR || 'data'); mkdirSync(dir, { recursive: true, mode: 0o700 });
const store = openStore(resolve(dir, 'railradar.sqlite'), () => webpush.generateVAPIDKeys());
webpush.setVapidDetails(config.origin, store.vapid.publicKey, store.vapid.privateKey);
const sendPush = (subscription, payload) => webpush.sendNotification(subscription, JSON.stringify(payload), { TTL: 60, urgency: 'high', timeout: 10000 });
const ns = createHandler({ key: process.env.NS_API_SUBSCRIPTION_KEY });
const monitor = createMonitor({ store, ns, sendPush, interval: seconds * 1000 });
const server = createApp({ config, store, ns, monitor, sendPush });
server.listen(Number(process.env.PORT || 3000), '0.0.0.0', () => { console.log('RailRadar listening; background monitor enabled.'); monitor.start(); });
for (const signal of ['SIGTERM','SIGINT']) process.on(signal, () => { monitor.stop(); server.close(() => process.exit(0)); setTimeout(() => process.exit(0), 25000).unref(); });
