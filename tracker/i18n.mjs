const COMPASS = { en: ['N', 'NE', 'E', 'SE', 'S', 'SW', 'W', 'NW'], nl: ['N', 'NO', 'O', 'ZO', 'Z', 'ZW', 'W', 'NW'] };
export function translate(lang, text, vars) {
  let result = lang === 'nl' ? (NL[text] ?? text) : text;
  if (vars) result = result.replace(/\{(\w+)\}/g, (match, key) => key in vars ? String(vars[key]) : match);
  return result;
}
export const compass = (lang, index) => (COMPASS[lang] || COMPASS.en)[((index % 8) + 8) % 8];
// Saved choice wins; otherwise follow the browser (Dutch for nl, nl-NL, nl-BE…).
export function pickLanguage(saved, browserLanguages = []) {
  if (LANGUAGES.includes(saved)) return saved;
  return browserLanguages.some(l => /^nl\b/i.test(l || '')) ? 'nl' : 'en';
}
